/**
 * One-time Play Store signing setup: upload keystore + android/keystore.properties
 *
 * Passwords (optional — random 32-char passwords generated if omitted):
 *   ANDROID_UPLOAD_KEYSTORE_PASSWORD
 *   ANDROID_UPLOAD_KEY_PASSWORD  (defaults to store password)
 *
 * Run: npm run cap:android:setup
 */
import { randomBytes } from 'node:crypto';
import { existsSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import { PATHS } from './lib/android-play-env.mjs';

const TAG = '[cap:android:setup]';

function log(msg) {
  console.log(`${TAG} ${msg}`);
}

function fail(msg) {
  console.error(`${TAG} ${msg}`);
  process.exit(1);
}

function findKeytool() {
  const name = process.platform === 'win32' ? 'keytool.exe' : 'keytool';
  const candidates = [];

  if (process.env.JAVA_HOME) {
    candidates.push(path.join(process.env.JAVA_HOME, 'bin', name));
  }

  if (process.platform === 'win32') {
    const where = spawnSync('where', ['keytool'], { encoding: 'utf8', shell: true });
    if (where.status === 0 && where.stdout) {
      for (const line of where.stdout.trim().split(/\r?\n/)) {
        candidates.push(line.trim());
      }
    }
    const programFiles = process.env['ProgramFiles'] || 'C:\\Program Files';
    candidates.push(
      path.join(programFiles, 'Android', 'Android Studio', 'jbr', 'bin', name),
      path.join(programFiles, 'Eclipse Adoptium', 'jdk-21.0.10.7-hotspot', 'bin', name),
    );
  }

  candidates.push(name);

  for (const candidate of candidates) {
    if (!candidate) continue;
    const probe = spawnSync(candidate, ['-version'], {
      encoding: 'utf8',
      shell: process.platform === 'win32',
    });
    if (!probe.error && probe.status === 0) {
      return candidate;
    }
  }
  return null;
}

function randomPassword() {
  return randomBytes(24).toString('base64url');
}

function writeKeystoreProperties(storePassword, keyPassword) {
  const relStore = 'nomnom-upload.keystore';
  const lines = [
    '# Generated by npm run cap:android:setup — do not commit',
    `storeFile=${relStore}`,
    `storePassword=${storePassword}`,
    'keyAlias=nomnom',
    `keyPassword=${keyPassword}`,
    '',
  ];
  writeFileSync(PATHS.keystoreProps, lines.join('\n'), 'utf8');
}

function writeSecretsBackup(storePassword, keyPassword) {
  const text = [
    'NomNom Android upload keystore (BACK UP OFFLINE — gitignored)',
    `Created: ${new Date().toISOString()}`,
    '',
    `Keystore file: android/nomnom-upload.keystore`,
    'Alias: nomnom',
    `Store password: ${storePassword}`,
    `Key password: ${keyPassword}`,
    '',
    'Play Console: https://play.google.com/console',
    'Package: com.nomnom.app',
    '',
    'If you lose this keystore you cannot publish updates under the same app signing key.',
    '',
  ].join('\n');
  writeFileSync(PATHS.credentialsBackup, text, 'utf8');
}

if (existsSync(PATHS.keystoreProps) && existsSync(PATHS.keystoreFile)) {
  log('Already configured (keystore + keystore.properties exist). Nothing to do.');
  process.exit(0);
}

if (existsSync(PATHS.keystoreProps) && !existsSync(PATHS.keystoreFile)) {
  fail('keystore.properties exists but nomnom-upload.keystore is missing. Restore the keystore or delete keystore.properties and re-run setup.');
}

if (existsSync(PATHS.keystoreFile) && !existsSync(PATHS.keystoreProps)) {
  fail('Keystore file exists but keystore.properties is missing. Copy keystore.properties.example and fill in passwords, or delete the .keystore and re-run setup.');
}

const keytool = findKeytool();
if (!keytool) {
  fail(
    'keytool not found. Install JDK 21+ and ensure JAVA_HOME is set, or add keytool to PATH (comes with Android Studio).',
  );
}

const storePassword = process.env.ANDROID_UPLOAD_KEYSTORE_PASSWORD?.trim() || randomPassword();
const keyPassword = process.env.ANDROID_UPLOAD_KEY_PASSWORD?.trim() || storePassword;

const dname =
  process.env.ANDROID_KEYSTORE_DN?.trim() ||
  'CN=NomNom, OU=Mobile, O=NomNom, L=Lisbon, ST=Lisbon, C=PT';

log('Generating upload keystore (RSA 2048, 10000 days)…');

const gen = spawnSync(
  keytool,
  [
    '-genkeypair',
    '-v',
    '-storetype',
    'PKCS12',
    '-keystore',
    PATHS.keystoreFile,
    '-alias',
    'nomnom',
    '-keyalg',
    'RSA',
    '-keysize',
    '2048',
    '-validity',
    '10000',
    '-storepass',
    storePassword,
    '-keypass',
    keyPassword,
    '-dname',
    dname,
  ],
  { stdio: 'inherit', shell: false, windowsHide: true },
);

if (gen.status !== 0) {
  fail('keytool failed. See output above.');
}

writeKeystoreProperties(storePassword, keyPassword);
writeSecretsBackup(storePassword, keyPassword);

log('Created:');
log(`  ${PATHS.keystoreFile}`);
log(`  ${PATHS.keystoreProps}`);
log(`  ${PATHS.credentialsBackup}  ← back this up to a password manager, then delete if you prefer`);
log('');
log('Next: create the app in Google Play Console (com.nomnom.app) if you have not already.');
log('Then for each release: npm run cap:android:release');
